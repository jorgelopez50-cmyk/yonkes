create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  signup_phone text;
  signup_terms_version text;
begin
  if new.raw_user_meta_data ->> 'terms_accepted' is distinct from 'true' then
    raise exception 'Debes aceptar los términos de uso y el aviso de privacidad para crear una cuenta.';
  end if;

  signup_terms_version := new.raw_user_meta_data ->> 'terms_version';
  if signup_terms_version is distinct from '1.0' then
    raise exception 'La versión de los términos cambió. Actualiza la página e inténtalo de nuevo.';
  end if;

  signup_phone := nullif(regexp_replace(coalesce(new.raw_user_meta_data ->> 'phone', ''), '[^0-9]', '', 'g'), '');
  if signup_phone is null or signup_phone !~ '^[1-9][0-9]{7,14}$' then
    raise exception 'El teléfono debe incluir el código de país y tener entre 8 y 15 dígitos.';
  end if;

  insert into public.profiles (id, role, email, phone, terms_accepted_at, terms_version)
  values (new.id, 'user', new.email, signup_phone, now(), signup_terms_version)
  on conflict (id) do update
  set email = excluded.email,
      phone = coalesce(public.profiles.phone, excluded.phone),
      terms_accepted_at = coalesce(public.profiles.terms_accepted_at, excluded.terms_accepted_at),
      terms_version = coalesce(public.profiles.terms_version, excluded.terms_version);
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

insert into public.profiles (id, role)
select id, 'user'
from auth.users
on conflict (id) do nothing;

