create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'user' check (role in ('admin', 'user')),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;

grant select on public.profiles to authenticated;

drop policy if exists "Users can read their own profile" on public.profiles;
create policy "Users can read their own profile"
  on public.profiles for select
  to authenticated
  using (auth.uid() = id);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, role)
  values (new.id, 'user')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

insert into public.profiles (id, role)
select id, 'user'
from auth.users
on conflict (id) do nothing;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid())
      and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create table if not exists public.parts (
  id bigint generated by default as identity primary key,
  code text not null default '',
  name text not null,
  category text not null default '',
  brand text not null default '',
  model text not null default '',
  year_from integer,
  year_to integer,
  condition text not null default 'Bueno'
    check (condition in ('Excelente', 'Bueno', 'Regular', 'Para reparar')),
  price numeric not null default 0,
  stock integer not null default 0,
  location text not null default '',
  donor_vehicle text not null default '',
  image text not null default '',
  notes text not null default ''
);

alter table public.parts
  add column if not exists owner_id uuid default auth.uid() references auth.users(id) on delete cascade;

alter table public.parts enable row level security;

grant select, insert, update, delete on public.parts to anon, authenticated;

drop policy if exists "Public can read parts" on public.parts;
create policy "Public can read parts"
  on public.parts for select
  to anon, authenticated
  using (true);

drop policy if exists "Authenticated users can add parts" on public.parts;
create policy "Authenticated users can add parts"
  on public.parts for insert
  to authenticated
  with check (auth.uid() = owner_id);

drop policy if exists "Owners can edit parts" on public.parts;
create policy "Owners can edit parts"
  on public.parts for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "Owners can delete parts" on public.parts;
create policy "Owners can delete parts"
  on public.parts for delete
  to authenticated
  using (public.is_admin());
