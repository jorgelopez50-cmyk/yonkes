set email = auth_user.email
from auth.users as auth_user
where profile.id = auth_user.id
  and profile.email is distinct from auth_user.email;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid())
      and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create or replace function public.update_my_phone(new_phone text)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  normalized_phone text;
begin
  if auth.uid() is null then
    raise exception 'Debes iniciar sesión para actualizar tu teléfono.';
  end if;

  normalized_phone := regexp_replace(coalesce(new_phone, ''), '[^0-9]', '', 'g');
  if normalized_phone !~ '^[1-9][0-9]{7,14}$' then
    raise exception 'Ingresa un número con código de país y entre 8 y 15 dígitos.';
  end if;

  update public.profiles
  set phone = normalized_phone
  where id = (select auth.uid());

  if not found then
    raise exception 'No se encontró el perfil de tu cuenta.';
  end if;

  return normalized_phone;
end;
$$;

revoke all on function public.update_my_phone(text) from public;
grant execute on function public.update_my_phone(text) to authenticated;

