create table if not exists public.parts (
  id bigint generated by default as identity primary key,
  code text not null default '',
  name text not null,
  category text not null default '',
  brand text not null default '',
  model text not null default '',
  year_from integer,
  year_to integer,
  condition text not null default 'Bueno'
    check (condition in ('Excelente', 'Bueno', 'Regular', 'Para reparar')),
  price numeric not null default 0,
  stock integer not null default 0,
  location text not null default '',
  donor_vehicle text not null default '',
  image text not null default '',
  notes text not null default ''
);

alter table public.parts
  add column if not exists owner_id uuid default auth.uid() references auth.users(id) on delete cascade;

create or replace view public.seller_whatsapp as
select profile.id as owner_id,
       profile.phone
from public.profiles as profile
where profile.phone ~ '^[1-9][0-9]{7,14}$'
  and exists (
    select 1
    from public.parts as part
    where part.owner_id = profile.id
      and part.stock > 0
  );

comment on view public.seller_whatsapp is
  'Public contact endpoint: exposes WhatsApp numbers only for accounts with available products.';

revoke all on public.seller_whatsapp from public, anon, authenticated;
grant select on public.seller_whatsapp to anon, authenticated;

